function Get_UserPassword () {
/bin/echo "${FUNCNAME[0]}"
Open_app
DisplayDialogMessage="Your admin password is required for this process:"
/bin/echo "${DisplayDialogMessage}"
title="Password"
icon="/System/Library/CoreServices/CoreTypes.bundle/Contents/Resources/FileVaultIcon.icns"
if [[ -e ${icon} ]] ; then
	UserPassword=$(/usr/bin/osascript -e "display dialog \"${DisplayDialogMessage}\" default answer \"\" with hidden answer with title \"${title}\" with icon POSIX file \"${icon}\"" -e "return text returned of result")
else
	UserPassword=$(/usr/bin/osascript -e "display dialog \"${DisplayDialogMessage}\" default answer \"\" with hidden answer with title \"${title}\"" -e "return text returned of result")
fi

if [ $? -eq 1 ]; then
	/bin/echo "User canceled - Exiting"
	Quit_or_Run_Again
fi
TRY=1
until /usr/bin/dscl /Search -authonly "$currentUser" "$UserPassword" &>/dev/null; do
    (( TRY++ ))
    DisplayDialogMessage="The password was incorrect. Please try again:"
    /bin/echo "Prompting $currentUser for their Mac password (attempt $TRY)..."
	if [[ -e ${icon} ]] ; then
		UserPassword=$(/usr/bin/osascript -e "display dialog \"${DisplayDialogMessage}\" default answer \"\" with hidden answer with title \"${title}\" with icon POSIX file \"${icon}\"" -e "return text returned of result")
	else
		UserPassword=$(/usr/bin/osascript -e "display dialog \"${DisplayDialogMessage}\" default answer \"\" with hidden answer with title \"${title}\"" -e "return text returned of result")
	fi
	if [ $? -eq 1 ]; then
		/bin/echo "User canceled ${button1} - Exiting"
		Quit_or_Run_Again
	elif (( TRY >= 3 )); then
	    DisplayDialogMessage="You've made three incorrect password attempts. Exiting now."
		button1="Quit"
		if [[ -e ${icon} ]] ; then
			/usr/bin/osascript -e "display dialog \"${DisplayDialogMessage}\" with title \"${title}\" with icon POSIX file \"${icon}\" buttons {\"${button1}\"} default button 1"
		else
			/usr/bin/osascript -e "display dialog \"${DisplayDialogMessage}\" with title \"${title}\" buttons {\"${button1}\"} default button 1"
		fi
		Quit_or_Run_Again 
    fi
done

if [[ -z "${UserPassword}" ]] ; then
	/bin/echo UserPassword not defined
	/bin/echo Exiting now
	Quit_or_Run_Again
fi
DisplayDialogMessage=""
# /bin/echo "End ${FUNCNAME[0]}"
}
