### Define Branch ###
function Define_Branch () {
Open_app
/usr/bin/clear
/usr/bin/printf "REFRESH\n"
/bin/echo "${FUNCNAME[0]}"
if [[ "${sw_build}" == "19" ]] ; then
	defaultBranch="catalina"
	/bin/echo "macOS ${sw_vers_Full} detected."
elif [[ "${sw_build}" == "20" ]] ; then
	defaultBranch="big_sur"
	/bin/echo "macOS ${sw_vers_Full} detected."
elif [[ "${sw_build}" == "21" ]] ; then
	defaultBranch="monterey"
	/bin/echo "macOS ${sw_vers_Full} detected."
elif [[ "${sw_build}" == "22" ]] ; then
	defaultBranch="ventura"
	/bin/echo "macOS ${sw_vers_Full} detected."
elif [[ "${sw_build}" == "23" ]] ; then
	defaultBranch="future_version"
	/bin/echo "macOS ${sw_vers_Full} detected."
fi
/bin/echo "defaultBranch $defaultBranch"

Branches=$(/usr/bin/git ls-remote --heads ${mSCP_github_URL} | /usr/bin/awk -F "/" '{print $NF}')
# Prune the main branch
PrunedBranches=$(/usr/bin/grep -v -w "main" <<< "$Branches")
prod_Branches=$(/usr/bin/printf "${PrunedBranches}" | /usr/bin/grep -v "dev_")
dev_Branches=$(/usr/bin/printf "${PrunedBranches}" | /usr/bin/grep "dev_")

items="${prod_Branches}\n${dev_Branches}\n"
DisplayDialogMessage="You are currently running macOS ${sw_vers_Full} ${macOSName}.

Please select a macOS Security Compliance Project branch from the list:"
title="Choose Branch"
#itemsToList=$(/usr/bin/printf "${items}" | /usr/bin/sort -u | /usr/bin/sed 's/^/\"/' | /usr/bin/sed 's/$/\"/' | /usr/bin/tr "\n" "," | /usr/bin/sed 's/.$//')
itemsToList=$(/usr/bin/printf "${items}" | /usr/bin/sed 's/^/\"/' | /usr/bin/sed 's/$/\"/' | /usr/bin/tr "\n" "," | /usr/bin/sed 's/.$//')
/bin/echo "${DisplayDialogMessage}"
# /bin/echo "${itemsToList}"
## Prompt for a Branch selection
chosenItem=$(/usr/bin/osascript -e 'choose from list {'"$itemsToList"'} with prompt "'"$DisplayDialogMessage"'" with title "'"$title"'" default items "'"$defaultBranch"'"')
macos_security_branch="${chosenItem}"
/bin/echo "Branch chosen ${macos_security_branch}"
if [[ "${chosenItem}" == "false" ]] ; then
	/bin/echo mSCP branch not defined
	/bin/echo Exiting now
	Quit_or_Run_Again
fi
DisplayDialogMessage=""
# /bin/echo "End ${FUNCNAME[0]}"
/bin/echo ""
}
