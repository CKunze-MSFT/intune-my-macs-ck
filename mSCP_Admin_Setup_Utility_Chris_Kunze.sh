/usr/bin/printf "REFRESH\n"
/bin/echo "${FUNCNAME[0]}"
DisplayDialogMessage="Do you want to quit now or run the utility again?"
/bin/echo "${DisplayDialogMessage}"
title="Quit or Run Again"
button1="Quit"
button2="Run Again"
DisplayDialogButtonReturned=$(/usr/bin/osascript -e "button returned of (display dialog \"${DisplayDialogMessage}\" with title \"${title}\" buttons {\"${button1}\",\"${button2}\"})")
/usr/bin/clear
/usr/bin/printf "REFRESH\n"
/bin/echo "${DisplayDialogButtonReturned}"
if [[ "${DisplayDialogButtonReturned}" == "${button1}" ]] ; then
	# Quit
	DisplayDialogMessage=""
	Quit_Project
elif [[ "${DisplayDialogButtonReturned}" == "${button2}" ]] ; then
	# Run Again
	DisplayDialogMessage=""
	run_Project
fi
# /bin/echo "End ${FUNCNAME[0]}"
/bin/echo ""
}
