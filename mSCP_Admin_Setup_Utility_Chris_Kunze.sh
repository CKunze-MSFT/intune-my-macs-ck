function Generate_Guidance () {
Open_app
/usr/bin/clear
/bin/echo "${FUNCNAME[0]}"
DisplayDialogMessage="Do you want to customize the ${Selected_Baseline} guidance report with a logo?

Square or horizontal format at least 1000px x 1000px is recommended."
/bin/echo "${DisplayDialogMessage}"
title="Logo"
button1="Yes"
button2="No"
DisplayDialogButtonReturned=$(/usr/bin/osascript -e "button returned of (display dialog \"${DisplayDialogMessage}\" with title \"${title}\" buttons {\"${button1}\",\"${button2}\"})")
/usr/bin/clear
/usr/bin/printf "REFRESH\n"
/bin/echo "User clicked ${DisplayDialogButtonReturned}"
if [[ "${DisplayDialogButtonReturned}" == "${button1}" ]] ; then
	Open_app
	/bin/echo "Select a logo"
	title="Logo File"
	DisplayDialogMessage="Please select a logo file to use with the project. Square or horizontal format at least 1000px x 1000px is recommended."
	button1="Proceed"
	LOGO_Path=$(/usr/bin/osascript -e "set theDocument to POSIX path of (choose file with prompt \"${DisplayDialogMessage}\")")
	if [[ -z "${LOGO_Path}" ]] ; then
		/bin/echo "A logo was not selected"
		Open_app
		/bin/echo "Generating guidance without a logo
		
Please be patient this may take some time.
"
		/bin/echo "generate_guidance command - ${python3_Path} ${ProjectDirectory}scripts/generate_guidance.py"
		"${python3_Path}" "${ProjectDirectory}scripts/generate_guidance.py" -s -p -x "${ProjectDirectory}build/baselines/${Selected_Baseline}.yaml"
	else
		#Establish target pixelHeight and target pixelWidth
		target_pixelHeight="1000"
		target_pixelWidth="2000"
		
		/bin/echo "LOGO_Path is ${LOGO_Path}"
		LOGO_Dir=$(/usr/bin/dirname "${LOGO_Path}")
		#/bin/echo "LOGO_Dir is ${LOGO_Dir}"
		LOGO_File=$(/usr/bin/basename "${LOGO_Path}")
		#/bin/echo "LOGO_File is ${LOGO_File}"
		LOGO_filename="${LOGO_File%.*}"
		#/bin/echo "LOGO_filename is ${LOGO_filename}"
		LOGO_extension="${LOGO_File##*.}"
		#/bin/echo "LOGO_extension is ${LOGO_extension}"
		LOGO_new="${ProjectDirectory}build/${LOGO_filename}-${target_pixelHeight}x${target_pixelWidth}.${LOGO_extension}"
		/bin/echo "LOGO_new is ${LOGO_new}"
		/bin/cp "${LOGO_Path}" "${LOGO_new}"

		# Determine current pixelWidth and pixelHeight
		LOGO_new_pixelHeight=$(/usr/bin/sips --getProperty pixelHeight "${LOGO_new}" 2> /dev/null | /usr/bin/awk '/pixelHeight:/{print $2}')
		LOGO_new_pixelWidth=$(/usr/bin/sips --getProperty pixelWidth "${LOGO_new}" 2> /dev/null | /usr/bin/awk '/pixelWidth:/{print $2}')
		/bin/echo "Starting LOGO_new_pixelHeight: ${LOGO_new_pixelHeight}"
		/bin/echo "Starting LOGO_new_pixelWidth: ${LOGO_new_pixelWidth}"

		# Adjust pixel width and height for horizontal logo file
		if [[ ${LOGO_new_pixelHeight} -lt ${LOGO_new_pixelWidth} ]]; then
			/bin/echo "Working with a horizontal logo"
			/usr/bin/sips --resampleHeight ${target_pixelHeight} "${LOGO_new}"
			LOGO_new_pixelHeight=$(/usr/bin/sips --getProperty pixelHeight "${LOGO_new}" 2> /dev/null | /usr/bin/awk '/pixelHeight:/{print $2}')
			LOGO_new_pixelWidth=$(/usr/bin/sips --getProperty pixelWidth "${LOGO_new}" 2> /dev/null | /usr/bin/awk '/pixelWidth:/{print $2}')
			if [[ ${LOGO_new_pixelWidth} -gt ${target_pixelWidth} ]]; then
				/bin/echo "resampleWidth ${target_pixelWidth}"
				/usr/bin/sips --resampleWidth ${target_pixelWidth} "${LOGO_new}"
			fi
			LOGO_new_pixelHeight=$(/usr/bin/sips --getProperty pixelHeight "${LOGO_new}" 2> /dev/null | /usr/bin/awk '/pixelHeight:/{print $2}')
			LOGO_new_pixelWidth=$(/usr/bin/sips --getProperty pixelWidth "${LOGO_new}" 2> /dev/null | /usr/bin/awk '/pixelWidth:/{print $2}')
			if [[ ${LOGO_new_pixelHeight} -gt ${target_pixelHeight} ]]; then
				/bin/echo "resampleHeight ${target_pixelHeight}"
				/usr/bin/sips --resampleHeight ${target_pixelHeight} "${LOGO_new}"
			fi
			/bin/echo "cropToHeightWidth ${target_pixelHeight} ${target_pixelWidth}"
			/usr/bin/sips --cropToHeightWidth ${target_pixelHeight} ${target_pixelWidth} "${LOGO_new}"
			#
			LOGO_new_pixelHeight=$(/usr/bin/sips --getProperty pixelHeight "${LOGO_new}" 2> /dev/null | /usr/bin/awk '/pixelHeight:/{print $2}')
			LOGO_new_pixelWidth=$(/usr/bin/sips --getProperty pixelWidth "${LOGO_new}" 2> /dev/null | /usr/bin/awk '/pixelWidth:/{print $2}')
		fi
		
		# Adjust pixel width and height for square or verticle logo file
		if [[ ${LOGO_new_pixelHeight} -gt ${LOGO_new_pixelWidth} ]] || [[ ${LOGO_new_pixelHeight} -eq ${LOGO_new_pixelWidth} ]]; then
			/bin/echo "Workinging with a square or verticle logo"
			/usr/bin/sips --resampleWidth ${target_pixelWidth} "${LOGO_new}"
			LOGO_new_pixelHeight=$(/usr/bin/sips --getProperty pixelHeight "${LOGO_new}" 2> /dev/null | /usr/bin/awk '/pixelHeight:/{print $2}')
			LOGO_new_pixelWidth=$(/usr/bin/sips --getProperty pixelWidth "${LOGO_new}" 2> /dev/null | /usr/bin/awk '/pixelWidth:/{print $2}')
			if [[ ${LOGO_new_pixelHeight} -gt ${target_pixelHeight} ]]; then
				/bin/echo "resampleHeight ${target_pixelHeight}"
				/usr/bin/sips --resampleHeight ${target_pixelHeight} "${LOGO_new}"
			fi
			/bin/echo "cropToHeightWidth ${target_pixelHeight} ${target_pixelWidth}"
			/usr/bin/sips --cropToHeightWidth ${target_pixelHeight} ${target_pixelWidth} "${LOGO_new}"
			#
			LOGO_new_pixelHeight=$(/usr/bin/sips --getProperty pixelHeight "${LOGO_new}" 2> /dev/null | /usr/bin/awk '/pixelHeight:/{print $2}')
			LOGO_new_pixelWidth=$(/usr/bin/sips --getProperty pixelWidth "${LOGO_new}" 2> /dev/null | /usr/bin/awk '/pixelWidth:/{print $2}')
		fi

		/bin/echo "Final LOGO_new_pixelHeight: ${LOGO_new_pixelHeight}"
		/bin/echo "Final LOGO_new_pixelWidth: ${LOGO_new_pixelWidth}"

		Open_app
		/bin/echo "Generating guidance with a logo.
		
Please be patient this may take some time.
"
		/bin/echo "generate_guidance command - ${python3_Path} ${ProjectDirectory}scripts/generate_guidance.py"
		"${python3_Path}" "${ProjectDirectory}scripts/generate_guidance.py" -s -p -x -l "${LOGO_new}" "${ProjectDirectory}build/baselines/${Selected_Baseline}.yaml"
	fi
elif [[ "${DisplayDialogButtonReturned}" == "${button2}" ]] ; then
	Open_app
	/bin/echo "Generating guidance without a logo
		
Please be patient this may take some time.
"
	/bin/echo "generate_guidance command - ${python3_Path} ${ProjectDirectory}scripts/generate_guidance.py"
	"${python3_Path}" "${ProjectDirectory}scripts/generate_guidance.py" -s -p -x "${ProjectDirectory}build/baselines/${Selected_Baseline}.yaml"
fi

### Check for generate_guidance.py errors
if [[ "$?" == "1" ]] ; then
	Bad_YAML
fi
DisplayDialogMessage=""

Create_Extension_Attributes

Create_ReadMe_rtf_within_baseline_directory

