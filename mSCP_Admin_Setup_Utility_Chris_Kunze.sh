### Install Xcode command line tools via command line ###
function Install_Xcode_command_line_tools_via_command_line () {
Open_app
/usr/bin/clear
/usr/bin/printf "REFRESH\n"
/bin/echo "${FUNCNAME[0]}"
if ! Are_command_line_tools_installed ; then
	# /usr/bin/clear
	/bin/echo "Checking for Xcode command line tools"
	# Create the placeholder file which is checked by the softwareupdate tool 
	# before allowing the installation of the Xcode command line tools.
	cmd_line_tools_temp_file="/tmp/.com.apple.dt.CommandLineTools.installondemand.in-progress"
	/usr/bin/touch "$cmd_line_tools_temp_file"
	cmd_line_tools=$(/usr/sbin/softwareupdate -l | /usr/bin/awk '/\*\ Label: Command Line Tools/ { $1=$1;print }' | /usr/bin/sed 's/^[[ \t]]*//;s/[[ \t]]*$//;s/*//' | /usr/bin/cut -c 9- | /usr/bin/grep -v beta)
	# Check to see if the softwareupdate tool has returned more than one Xcode
	# command line tool installation option. If it has, use the last one listed
	# as that should be the latest Xcode command line tool installer.
	if (( $(/usr/bin/grep -c . <<<"$cmd_line_tools") > 1 )); then
		cmd_line_tools_output="$cmd_line_tools"
		cmd_line_tools=$(/usr/bin/printf "$cmd_line_tools_output" | /usr/bin/tail -1)
		DisplayDialogMessage="Installing ${cmd_line_tools}. 

Please be patient this may take some time.

This message will close when complete."
		/bin/echo "${DisplayDialogMessage}"
		title="Xcode command line tools"
		button1="Ok"
		icon="/System/Library/CoreServices/Install Command Line Developer Tools.app/Contents/Resources/SoftwareUpdate.icns"
		if [[ -e ${icon} ]] ; then
			/usr/bin/osascript -e "display dialog \"${DisplayDialogMessage}\" with title \"${title}\" with icon POSIX file \"${icon}\" buttons {\"${button1}\"} default button 1" &
		else
			/usr/bin/osascript -e "display dialog \"${DisplayDialogMessage}\" with title \"${title}\" buttons {\"${button1}\"} default button 1" &
		fi
		#Install the command line tools
		/usr/sbin/softwareupdate -i "$cmd_line_tools" --verbose
		/usr/bin/killall osascript
		# Remove the temp file
		if [[ -f "$cmd_line_tools_temp_file" ]]; then
			/bin/rm "$cmd_line_tools_temp_file"
		fi
		if ! Are_command_line_tools_installed ; then
			Open_app
			/usr/bin/clear
			/usr/bin/printf "REFRESH\n"
			/bin/echo "Installation of Xcode command line tools failed from the command line. Switching to the slower GUI intallation method."
			DisplayDialogMessage=""
			Install_Xcode_command_line_tools_via_GUI
		fi
	else
		Open_app
		/usr/bin/clear
		/usr/bin/printf "REFRESH\n"
		/bin/echo "Installation of Xcode command line tools failed from the command line. Switching to the slower GUI intallation method."
		# Remove the temp file
		if [[ -f "$cmd_line_tools_temp_file" ]]; then
			/bin/rm "$cmd_line_tools_temp_file"
		fi
		Install_Xcode_command_line_tools_via_GUI
	fi
fi
/usr/bin/xcode-select -v 2> /dev/null
# /bin/echo "End ${FUNCNAME[0]}"
/bin/echo ""
}
